export function officeAnalogyForTool(toolName: string): OfficeToolAnalogy | undefined {
  const exact = OFFICE_TOOL_ATLAS.find((item) => item.toolNames.includes(toolName));
  return (
    exact ??
    (toolName.startsWith('mcp_') || toolName.startsWith('integration_')
      ? OFFICE_TOOL_ATLAS.find((item) => item.id === 'integration')
      : undefined)
  );
}
