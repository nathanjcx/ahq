export type OfficeStation =
  | 'desk'
  | 'archive'
  | 'library'
  | 'dispatch'
  | 'workbench'
  | 'research'
  | 'analysis'
  | 'connections'
  | 'review'
  | 'recorder';
export interface OfficeToolAnalogy {
  id: string;
  label: string;
  mechanism: string;
  object: string;
  action: string;
  evidence: string;
  station: OfficeStation;
  toolNames: readonly string[];
  availability: 'core' | 'optional';
}
const entry = (
  id: string,
  label: string,
  mechanism: string,
  object: string,
  action: string,
  evidence: string,
  station: OfficeStation,
  toolNames: readonly string[] = [],
  availability: OfficeToolAnalogy['availability'] = 'core',
): OfficeToolAnalogy => ({
  id,
  label,
  mechanism,
  object,
  action,
  evidence,
  station,
  toolNames,
  availability,
});

